def add(a, b):
    """Returns the sum of two numbers."""
    return a + b


def subtract(a, b):
    """Returns the difference of two numbers."""
    return a - b


def multiply(a, b):
    """Returns the product of two numbers."""
    return a * b


if __name__ == "__main__":
    print("Сложение: 2 + 3 =", add(2, 3))
    print("Вычитание: 7 - 4 =", subtract(7, 4))
    print("Умножение: 2 * 4 =", multiply(2, 4))
